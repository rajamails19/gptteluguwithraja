export type Category =
  | "Animal Stories"
  | "Moral Stories"
  | "Beginner Telugu"
  | "Letters"
  | "Numbers"
  | "Rhymes"
  | "Daily Telugu";

export type AgeBand = "3–5" | "3–6" | "4–6" | "5–7" | "6–8" | "All ages";

export interface StoryPage {
  image: string;
  telugu: string;
  english: string;
  tamil?: string;
  tamilAudio?: string;
  tamilAudioBySpeed?: Record<string, string>;
  spanish?: string;
  spanishAudio?: string;
  spanishAudioBySpeed?: Record<string, string>;
  wordMap?: Record<string, string>;
  tamilWordMap?: Record<string, string>;
  spanishWordMap?: Record<string, string>;
  audio?: string;
  audioBySpeed?: {
    "0.05"?: string;
    "0.15"?: string;
    "0.25"?: string;
    "0.45"?: string;
    "0.5"?: string;
    "0.75"?: string;
    "1"?: string;
  };
  highlightBySpeed?: {
    "0.05"?: HighlightTimingProfile;
    "0.15"?: HighlightTimingProfile;
    "0.25"?: HighlightTimingProfile;
    "0.5"?: HighlightTimingProfile;
    "0.75"?: HighlightTimingProfile;
    "1"?: HighlightTimingProfile;
  };
  audioSequence?: {
    src: string;
    pauseAfterMs?: number;
    playbackRate?: number;
    volume?: number;
  }[];
  audioRepeat?: {
    count: number;
    pauseMs: number;
  };
}

export interface HighlightTimingProfile {
  chunkPattern: readonly number[];
  longChunkPattern?: readonly number[];
  longWordThreshold?: number;
  wordBaseUnits?: number;
  wordLengthUnits?: number;
  pauseUnits?: number;
  innerWordPauseUnits?: number;
  finalPauseUnits?: number;
}

export interface Story {
  id: string;
  title: string;
  teluguTitle: string;
  cover: string;
  category: Category;
  age: AgeBand;
  minutes: number;
  tagline: string;
  pages: StoryPage[];
  // Optional per-language page sets. When a language has its own full page
  // list (e.g. a complete Tamil/Spanish alphabet with more letters than the
  // Telugu base), the reader switches to it instead of just swapping text.
  pagesByLang?: {
    tamil?: StoryPage[];
    spanish?: StoryPage[];
  };
}

